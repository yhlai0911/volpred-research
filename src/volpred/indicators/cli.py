@cli.command()
@click.option(
    "--registry-path",
    default=None,
    help="Override path to registry.json.",
)
@click.option(
    "--json-output",
    is_flag=True,
    default=False,
    help="Output as JSON.",
)
def status(registry_path: str | None, json_output: bool) -> None:
    """Show indicator registry status summary."""
    reg_path = Path(registry_path) if registry_path else None
    try:
        all_specs = load_registry(reg_path)
    except FileNotFoundError as exc:
        click.echo(f"Error: {exc}", err=True)
        sys.exit(1)

    counts: dict[str, int] = {"active": 0, "observation": 0, "delisted": 0}
    rows = []
    for spec in all_specs:
        counts[spec.status] = counts.get(spec.status, 0) + 1
        rows.append(
            {
                "indicator_id": spec.indicator_id,
                "name_zh": spec.name_zh,
                "league": spec.league,
                "status": spec.status,
                "horizon_days": spec.horizon_days,
                "k_refs": spec.k_refs,
            }
        )

    if json_output:
        click.echo(
            json.dumps(
                {"summary": counts, "indicators": rows},
                indent=2,
                ensure_ascii=False,
            )
        )
    else:
        click.echo(
            f"Indicator Arena — {counts['active']} active, "
            f"{counts['observation']} observation, "
            f"{counts['delisted']} delisted "
            f"(total {len(all_specs)})"
        )
        for row in rows:
            click.echo(
                f"  [{row['status'].upper():<11}] {row['indicator_id']:<35} "
                f"league={row['league']:<13} horizon={row['horizon_days']}d "
                f"k_refs={row['k_refs']}"
            )


