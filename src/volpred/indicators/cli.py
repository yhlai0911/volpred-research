# emit
# ---------------------------------------------------------------------------

@cli.command()
@click.argument("indicator_id")
@click.option(
    "--dry-run",
    is_flag=True,
    default=False,
    help="Print the signal payload without writing to disk.",
)
@click.option(
    "--registry-path",
    default=None,
    help="Override path to registry.json (for testing).",
)
def emit(indicator_id: str, dry_run: bool, registry_path: str | None) -> None:
    """Emit a signal scaffold for INDICATOR_ID.

    In production the actual signal values are injected by the daily pipeline
    (scripts/indicator_arena_daily.py). This command validates that the
    indicator_id exists and prints the required field template.
    """
    reg_path = Path(registry_path) if registry_path else None
    spec = get_by_id(indicator_id, path=reg_path)
    if spec is None:
        click.echo(
            f"Error: unknown indicator_id '{indicator_id}'. "
            "Run 'indicator-arena status' to see valid IDs.",
            err=True,
        )
        sys.exit(1)

    if spec.status == "delisted":
        click.echo(
            f"Error: indicator '{indicator_id}' is delisted and cannot emit signals.",
            err=True,
        )
        sys.exit(1)

    now = datetime.now(timezone.utc).isoformat()
    scaffold: dict[str, Any] = {
        "signal_id": "<uuid — auto-generated by append_signal>",
        "indicator_id": indicator_id,
        "as_of_ts": f"<REQUIRED: data cutoff, must be ≤ {now}>",
        "emitted_at": now,
        "prediction": f"<REQUIRED: dict, e.g. {{direction: up}} for league={spec.league}>",
        "horizon_days": spec.horizon_days,
        "expires_at": "<REQUIRED: as_of_ts + horizon_days trading days, ISO UTC>",
        "data_hash": "<REQUIRED: sha256 of raw inputs dict>",
        "code_version": _get_git_short_sha(),
        "indicator_value": "<optional: raw numeric value>",
        "inputs_snapshot": "<optional: dict of input values used>",
    }
    if dry_run:
        click.echo("-- DRY RUN: signal scaffold (not written) --")
        click.echo(json.dumps(scaffold, indent=2, ensure_ascii=False))
    else:
        click.echo(json.dumps(scaffold, indent=2, ensure_ascii=False))


