@cli.command(name="review-due")
@click.option(
    "--signals-dir",
    default=None,
    help="Override path to signals/ directory.",
)
@click.option(
    "--reviews-dir",
    default=None,
    help="Override path to reviews/ directory.",
)
def review_due(signals_dir: str | None, reviews_dir: str | None) -> None:
    """List signals whose resolve_after time has passed but have no review yet."""
    sig_dir = Path(signals_dir) if signals_dir else SIGNALS_DIR
    rev_dir = Path(reviews_dir) if reviews_dir else REVIEWS_DIR

    now = datetime.now(timezone.utc)

    # Collect all signals from all JSONL files
    all_signals: list[dict[str, Any]] = []
    if sig_dir.exists():
        for f in sorted(sig_dir.glob("*.jsonl")):
            year_month = f.stem
            all_signals.extend(read_signals(year_month, sig_dir))

    # Collect all reviewed signal_ids
    reviewed_ids: set[str] = set()
    if rev_dir.exists():
        for f in sorted(rev_dir.glob("*.jsonl")):
            year_month = f.stem
            for row in read_reviews(year_month, rev_dir):
                reviewed_ids.add(row.get("signal_id", ""))

    # Find due-but-unreviewed
    due: list[dict[str, Any]] = []
    for sig in all_signals:
        sid = sig.get("signal_id", "")
        if sid in reviewed_ids:
            continue
        resolve_after = sig.get("resolve_after")
        if resolve_after:
            try:
                resolve_dt = datetime.fromisoformat(
                    resolve_after.replace("Z", "+00:00")
                )
                if now >= resolve_dt:
                    due.append(sig)
            except (ValueError, TypeError):
                pass
        else:
            # No resolve_after set — treat as immediately due
            due.append(sig)

    if not due:
        click.echo("No signals due for review.")
        return

    click.echo(f"Signals due for review ({len(due)}):")
    for sig in due:
        click.echo(
            f"  {sig.get('signal_id', '?')} | {sig.get('indicator_id', '?')} "
            f"| as_of={sig.get('as_of_ts', '?')} "
            f"| resolve_after={sig.get('resolve_after', 'N/A')}"
        )


