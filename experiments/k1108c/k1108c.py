"""
K1108c: Continuous guide_delta_pct as capex covariate (replace binary).
========================================================================
[提出: 賴奕豪, 執行: Claude]  Date: 2026-04-17
Parent: K1108b (H2 DECISIVE NULL with binary flag; commit 5bcd8143)

Motivation
----------
K1108b pooled 5 foundry stocks (4 distinct firms) with a BINARY
guide_updated flag → pool Wald t=-0.0003, p=0.9997 → H2 DECISIVE NULL.
But a binary flag discards magnitude information: a ±1% revision is
treated the same as a ±60% MASSIVE RAISE. K1108c replaces the binary
split (θ_change vs θ_stable) with a SIGNED CONTINUOUS regressor
`guide_delta_pct` in [-69.6%, +136.8%] (pool range), allowing us to
test whether the MAGNITUDE of capex revision explains foundry θ₂ > 0.

Hypotheses:
  H1_MAGNITUDE_PASS: β₁ coefficient on guide_delta_pct is positive
                    AND HAC-robust |t| > 3.0 (Harvey 2016), AND
                    bootstrap 95% CI excludes 0 → capex MAGNITUDE is
                    the foundry mechanism (even though binary was null)
  H2_MAGNITUDE_NULL: |t| < 2.0 and bootstrap CI spans 0 → magnitude
                    AND direction both null → K1108b conclusion
                    strengthened: capex guidance is NOT the foundry
                    mechanism
  H3_MAGNITUDE_MARGINAL: 2.0 < |t| < 3.0 → magnitude has some power
                        but not Harvey-strong

Design
------
Two-stage regression approach (HAC-robust on stage 2):

  Stage 1 (per-firm τ_EAV extraction):
    For each firm i, refit the K1108b per-stock A4f-EAV model under
    the binary P3 spec (θ_change, θ_stable) to get empirical τ_it for
    each event day d.
    θ_EAV_{i,d} := τ̂_{i,d} − (θ̂_{0,i} + θ̂_{1,i}·VIX²_{d-1})
    = the event-day shift in long-memory component that K1104/K1108
      tests as "the foundry mechanism".

  Stage 2 (continuous magnitude test):
    Pool (i, d) observations into cross-section. Estimate
       θ_EAV_{i,d} = β₀ + β₁ · guide_delta_pct_{i,d} + ε_{i,d}
    with clustered-by-firm HAC-robust (Newey-West auto-BW per
    Andrews 1991) SE. Report point, t, 95% CI, bootstrap CI.

Robustness
  - Winsorize guide_delta_pct at [1%, 99%] pool percentiles
  - Block bootstrap β₁ (N=1000, block=10 events consecutive within firm)
  - Drop-firm LOO of Stage 2
  - Sign asymmetry check: separate β_pos (on guide_delta_pct⁺) and
    β_neg (on |guide_delta_pct⁻|); compare

Data provenance
  - Per-firm τ̂, θ̂₀, θ̂₁: K1108b per-stock fit coefficients
    (reused via `experiments/k1108b/k1108b.py` imported and refit on
     worktree-local snapshot — deterministic with seed=42)
  - guide_delta_pct: `experiments/k1108c/data/pooled_capex_guidance_mag.csv`
    generated by `k1108c_build_magnitude.py` from K1108/K1108b
    hand-coded dollar figures (no new external fetches)

Lookahead guard
  - All regressors lagged per K1108b convention (τ̂_{i,d} uses
    VIX²_{d-1}, EAV_{d-1})
  - guide_delta_pct_d is event-day announcement known at close
    (standard K1104/K1108/K1108b event-study window)
  - seed=42 everywhere; pandas/numpy/scipy deterministic
"""
