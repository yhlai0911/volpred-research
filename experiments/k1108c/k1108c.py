def decide_verdict(beta1, t_hac, ci_lo, ci_hi, se):
    bullets = []
    bullets.append(f"β₁ = {beta1:+.4e}  t_HAC = {t_hac:+.3f}")
    bullets.append(f"bootstrap 95% CI = [{ci_lo:+.4e}, {ci_hi:+.4e}]")
    bullets.append(f"HAC SE = {se:.4e}")

    ci_excludes_zero = (ci_lo > 0 and ci_hi > 0) or (ci_lo < 0 and ci_hi < 0)

    if np.isfinite(t_hac) and abs(t_hac) > 3.0 and ci_excludes_zero:
        label = 'H1_MAGNITUDE_PASS'
        bullets.append("H1 PASS: |t_HAC| > 3.0 (Harvey) AND 95% CI excludes 0")
        conclusion = (
            "Continuous magnitude REVEALS capex mechanism that binary "
            "flag missed. K1108b null was due to discarding magnitude info."
        )
    elif np.isfinite(t_hac) and abs(t_hac) > 2.0 and ci_excludes_zero:
        label = 'H3_MAGNITUDE_MARGINAL'
        bullets.append("H3 MARGINAL: 2.0 < |t_HAC| < 3.0 (suggestive but "
                       "not Harvey-strong)")
        conclusion = (
            "Magnitude signal present but below Harvey threshold. "
            "K1108b null partially softened."
        )
    elif np.isfinite(t_hac) and abs(t_hac) < 2.0:
        label = 'H2_MAGNITUDE_NULL'
        bullets.append("H2 NULL: |t_HAC| < 2.0 — magnitude AND direction both null")
        conclusion = (
            "K1108b binary-null conclusion STRENGTHENED. Capex guidance "
            "has NO explanatory power for foundry θ₂>0, whether as binary "
            "flag or signed continuous magnitude."
        )
    else:
        label = 'INCONCLUSIVE'
        bullets.append(f"INCONCLUSIVE: |t_HAC|={abs(t_hac):.3f} in [2,3] "
                       "but CI overlaps 0")
        conclusion = "Non-decisive — further testing needed."

    return {'label': label, 'bullets': bullets, 'conclusion_vs_binary': conclusion}


def plot_scatter(merged, beta1, beta0, t_hac, p_hac):
    fig, ax = plt.subplots(figsize=(9.5, 6))
    x = merged['guide_delta_pct_raw'].values
    y = merged['theta_eav_empirical'].values
    stocks = merged['stock'].values
    uniq = np.unique(stocks)
    colors = plt.cm.tab10(np.arange(len(uniq)))
    for s, c in zip(uniq, colors):
        m = stocks == s
        ax.scatter(x[m], y[m], s=28, alpha=0.65, label=s, color=c)
    # Fit line
    xs = np.linspace(x.min(), x.max(), 100)
    ax.plot(xs, beta0 + beta1 * xs, color='black', lw=2,
            label=f'Fit: β₁={beta1:+.2e} (t={t_hac:+.2f})')
    ax.axhline(0, color='gray', lw=0.6, ls='--')
    ax.axvline(0, color='gray', lw=0.6, ls='--')
    ax.set_xlabel('guide_delta_pct (%)')
    ax.set_ylabel('θ_EAV_empirical (event-day long-memory shift)')
    ax.set_title(f'K1108c: θ_EAV vs continuous capex guidance magnitude\n'
                 f't_HAC={t_hac:+.3f}, p={p_hac:.4f}, N={len(x)}')
    ax.legend(loc='best', fontsize=9)
    plt.tight_layout()
    plt.savefig(PLOT_SCATTER, dpi=120)
    plt.close()
    print(f"Saved {PLOT_SCATTER}")


