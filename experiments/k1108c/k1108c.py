def newey_west_bw(n):
    """Andrews (1991) automatic bandwidth for Newey-West HAC: floor(4*(T/100)^(2/9))."""
    return int(np.floor(4.0 * (n / 100.0) ** (2.0 / 9.0)))


def ols_hac(y, X, bw=None):
    """OLS with Newey-West HAC-robust SE.

    y: (n,) response vector
    X: (n, k) design matrix (with constant column if intercept desired)
    Returns dict with beta, cov_hac, se_hac, t_hac, p_hac, R², n.
    """
    n, k = X.shape
    XtX_inv = np.linalg.pinv(X.T @ X)
    beta = XtX_inv @ X.T @ y
    resid = y - X @ beta

    # HAC covariance (Newey-West)
    if bw is None:
        bw = max(newey_west_bw(n), 1)

    S0 = (X * resid[:, None]).T @ (X * resid[:, None]) / n
    S = S0.copy()
    for lag in range(1, bw + 1):
        w = 1.0 - lag / (bw + 1.0)
        Gamma = np.zeros((k, k))
        for t in range(lag, n):
            xt = X[t, :].reshape(-1, 1)
            xtl = X[t - lag, :].reshape(-1, 1)
            Gamma += (resid[t] * resid[t - lag]) * (xt @ xtl.T)
        Gamma /= n
        S += w * (Gamma + Gamma.T)

    cov_hac = n * XtX_inv @ S @ XtX_inv
    se_hac = np.sqrt(np.clip(np.diag(cov_hac), 0, None))
    t_hac = beta / np.where(se_hac > 0, se_hac, np.nan)
    p_hac = 2.0 * (1.0 - stats.norm.cdf(np.abs(t_hac)))

    ss_res = float((resid ** 2).sum())
    ss_tot = float(((y - y.mean()) ** 2).sum())
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else np.nan

    return {
        'beta': beta.tolist(),
        'se_hac': se_hac.tolist(),
        't_hac': t_hac.tolist(),
        'p_hac': p_hac.tolist(),
        'cov_hac': cov_hac.tolist(),
        'R2': float(r2),
        'n': int(n),
        'bw': int(bw),
        'ss_res': ss_res,
    }


def block_bootstrap_beta1(pool_df, y_col, x_col, n_reps=1000, block=10, seed=42):
    """Block-bootstrap β₁ CI. Blocks are drawn within each firm to preserve
    firm-level serial dependence.

    Returns array of β₁ replicates.
    """
    rng = np.random.default_rng(seed)
    betas = np.zeros(n_reps)
    firms = pool_df['stock'].unique()
    firm_frames = {f: pool_df.loc[pool_df['stock'] == f].reset_index(drop=True)
                   for f in firms}

    for r in range(n_reps):
        sampled_rows = []
        for f, df in firm_frames.items():
            n = len(df)
            if n == 0:
                continue
            n_blocks = int(np.ceil(n / block))
            for _ in range(n_blocks):
                start = rng.integers(0, max(n - block + 1, 1))
                sampled_rows.append(df.iloc[start:start + block])
        boot = pd.concat(sampled_rows, ignore_index=True)
        y = boot[y_col].values
        x = boot[x_col].values
        X = np.column_stack([np.ones(len(x)), x])
        try:
            XtX_inv = np.linalg.pinv(X.T @ X)
            b = XtX_inv @ X.T @ y
            betas[r] = b[1]
        except Exception:
            betas[r] = np.nan

    return betas[~np.isnan(betas)]


def winsorize(x, low_pct=1, high_pct=99):
    lo = np.percentile(x, low_pct)
    hi = np.percentile(x, high_pct)
    return np.clip(x, lo, hi)


