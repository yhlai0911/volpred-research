def extract_event_theta(frame, fit):
    """From per-stock A4f-EAV fit (θ₀, θ₁, θ_change, θ_stable, ω, α, γ, β),
    return θ_EAV_{d} = θ̂_change or θ̂_stable at each EAV day d.

    In the A4f-EAV spec, the long-memory component on event day d is
        τ_d = θ̂_0 + θ̂_1 · VIX²_{d-1}
              + θ̂_change · EAV_change_{d-1}
              + θ̂_stable · EAV_stable_{d-1}
    So the shift attributable to the event ("θ_EAV_{d}") is either
    θ̂_change (if EAV_change_{d-1}==1) or θ̂_stable (if EAV_stable_{d-1}==1).

    The lag-1 EAV means the event_day shift shows up at day d+1 on the
    trading calendar; K1108b convention positions event at the next
    trading close, so we associate θ_EAV with the event itself.

    For the CONTINUOUS covariate spec we return the fitted scalar
    θ̂_EAV that characterises the event response for that firm.
    """
    pp = fit['params']
    # _single_nll layout: [θ₀, θ₁, θ_change, θ_stable, ω, α, γ, β]
    theta_change = float(pp[2])
    theta_stable = float(pp[3])

    events = []
    ec_lag = frame['_EAV_change_lag'].values
    es_lag = frame['_EAV_stable_lag'].values
    dates = frame.index
    for t, (c, s) in enumerate(zip(ec_lag, es_lag)):
        if c == 1:
            events.append({'event_date': dates[t],
                           'theta_eav_fitted': theta_change,
                           'flag': 'change'})
        elif s == 1:
            events.append({'event_date': dates[t],
                           'theta_eav_fitted': theta_stable,
                           'flag': 'stable'})
    return events, theta_change, theta_stable


def per_event_theta_via_residual(frame, fit):
    """Alternative: instead of reusing the fitted θ̂_change/θ̂_stable (which
    is a single scalar per firm-flag), estimate θ_EAV_{i,d} by
    residualising the conditional long-memory variance at event d
    against its baseline prediction.

    θ_EAV_{i,d} := (empirical squared residual at d — GARCH-only prediction)
                 where GARCH-only prediction = (θ̂_0 + θ̂_1 · VIX²_{d-1}) · g_{i,d}
                 normalised by g_{i,d}

    This yields ONE scalar per event, allowing actual dispersion in the
    OLS stage and a valid continuous regression.
    """
    from numba import njit

    @njit(cache=True, fastmath=True)
    def _compute_g(returns, tau, omega, alpha, gamma_p, beta):
        n = returns.shape[0]
        persist = alpha + gamma_p / 2.0 + beta
        eg = omega / (1.0 - persist)
        g = np.zeros(n)
        g[0] = eg
        for t in range(1, n):
            tau_prev = tau[t - 1] if tau[t - 1] > 1e-16 else 1e-16
            u_prev = returns[t - 1] / np.sqrt(tau_prev)
            asym = gamma_p * u_prev ** 2 if u_prev < 0 else 0.0
            g[t] = omega + alpha * u_prev ** 2 + asym + beta * g[t - 1]
            if g[t] < 1e-10:
                g[t] = 1e-10
        return g

    pp = fit['params']
    theta0 = float(pp[0]); theta1 = float(pp[1])
    theta_change = float(pp[2]); theta_stable = float(pp[3])
    omega = float(pp[4]); alpha = float(pp[5])
    gamma_p = float(pp[6]); beta = float(pp[7])

    returns = frame['log_ret'].values
    vix2_lag = frame['_vix2_lag'].values
    ec_lag = frame['_EAV_change_lag'].values
    es_lag = frame['_EAV_stable_lag'].values

    tau = np.maximum(theta0 + theta1 * vix2_lag
                     + theta_change * ec_lag
                     + theta_stable * es_lag, 1e-16)
    g = _compute_g(returns, tau, omega, alpha, gamma_p, beta)

    dates = frame.index
    events = []
    for t in range(len(returns)):
        if ec_lag[t] == 1 or es_lag[t] == 1:
            flag = 'change' if ec_lag[t] == 1 else 'stable'
            # Empirical τ_d ≈ r_d² / g_d (conditional squared-return normalised by short-run)
            g_d = g[t] if g[t] > 1e-10 else 1e-10
            tau_empirical = returns[t] ** 2 / g_d
            baseline = theta0 + theta1 * vix2_lag[t]
            theta_eav_empirical = tau_empirical - baseline
            # fitted scalar from MLE
            if ec_lag[t] == 1:
                theta_fitted = theta_change
            else:
                theta_fitted = theta_stable
            events.append({
                'event_date': pd.Timestamp(dates[t]).strftime('%Y-%m-%d'),
                'flag': flag,
                'theta_eav_fitted': theta_fitted,
                'theta_eav_empirical': float(theta_eav_empirical),
                'r2_d': float(returns[t] ** 2),
                'g_d': float(g_d),
                'vix2_d_lag': float(vix2_lag[t]),
                'baseline_d': float(baseline),
            })
    return events


