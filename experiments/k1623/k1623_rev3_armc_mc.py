"""
K1623 rev3 — arm C: how much of the generated-regressor problem is MEAN estimation?
==================================================================================

WHY THIS SCRIPT EXISTS
----------------------
`k1623_rev2_mc.py` runs two arms and README §6.4 carries the resulting scope
limit as DISCLOSED, NOT FIXED:

  Arm A (realistic)        simulate -> Bai-Perron selects break COUNT + LOCATIONS -> demean -> ELW
  Arm B (partition-oracle) simulate -> demean at the TRUE break PARTITION -> ELW

Both arms re-ESTIMATE each segment's mean from the simulated data. The
uncertainty contributed by estimating the mean structure is therefore present in
both and CANCELS in the A-minus-B contrast: rev2 could not measure it and could
not bound it. That is the blocked item this script closes.

Arm C makes the level oracle too:

  Arm C (full oracle)     simulate -> subtract the KNOWN implanted level vector -> ELW

The three arms then decompose cleanly, on SHARED simulated paths:

  A - B  = cost of selecting the break PARTITION (count + locations; frozen in rev2)
  B - C  = cost of having to ESTIMATE the segment MEANS at known locations  <-- NEW
  A - C  = total generated-regressor cost = (A-B) + (B-C)
  C - d  = ELW's OWN finite-sample bias, with no break-driven segmented-mean regressor

Note what arm C is, numerically. The simulated series is x = fracint(eps) + level,
so x - level is the raw ARFIMA path. Arm C is therefore the break-free baseline
that rev2's README explicitly warned arm B was NOT.

One caveat that decides how B - C may be quoted: arm C is oracle in the SEGMENT
LEVEL structure, not zero-mean. `local_whittle(exact=True)` still subtracts a
single sample grand mean internally, as Shimotsu-Phillips ELW requires. So arm C
estimates ONE grand mean where arm B estimates n_breaks+1 segment means, and
B - C is the INCREMENTAL cost of the segment means over ELW's own standard
demeaning. That is the right comparison -- some demeaning is unavoidable on real
data -- but it is not "the cost of estimating any mean at all", and the artifact
says so in as many words so the number cannot be quoted as the stronger thing.

WHY THIS IS A SIBLING FILE AND NOT AN EDIT TO k1623_rev2_mc.py
--------------------------------------------------------------
`k1623_rev2_mc_results.json` is FROZEN evidence. Its current bytes are the rev2
run OUTPUT PLUS the rev3 remediation patch (`k1623_rev3_patch_mc_artifact.py`,
which added the 58-field `claim_corrections_rev3` block and superseded four
claims). Re-running `k1623_rev2_mc.py` calls atomic_write_json on that same path
and would silently destroy the patch block and rename summary keys. Adding arm C
by editing that script and re-running it would therefore MUTATE frozen fields,
which the task forbids. So arm C runs here and writes its own artifact; the rev2
JSON is opened read-only, as a reproduction target.

SHARED-PATH GUARANTEE (this is the whole point -- B-C is meaningless without it)
-------------------------------------------------------------------------------
Same SEED, same per-asset stream offset, same DGP, same N_REPS, same BURN, same
data vintage pin, all imported from `k1623_rev2_mc` rather than re-typed. Arm C
consumes no random numbers, so the eps stream is drawn exactly as in rev2.

That is the argument. The script does not rely on it -- it MEASURES it. Two
gates, both fail-closed:

  precondition gate   the fitted model this run conditions on (n, m, d_hat,
                      sigma, break count) must equal the frozen values
  reproduction gate   the re-run arm A and arm B mean/sd must equal the frozen
                      arm A and arm B mean/sd to rtol=1e-9

If the paths were not shared, arm B could not reproduce a frozen sd to nine
digits. If either gate fails the script raises and writes nothing, rather than
emitting a B-C contrast built on paths that do not line up.

WHAT THIS STILL DOES NOT DO
---------------------------
Everything rev2's scope limits already said. This is a MODEL-CONDITIONAL
exercise: it assumes the data really were generated by "ARFIMA(0, d, 0) +
deterministic level shifts at the estimated dates" and quantifies sampling
uncertainty UNDER THAT MODEL. Adding a third arm buys a finer ATTRIBUTION of
that uncertainty; it buys no evidence that the model is right, and it says
nothing about the Diebold-Inoue random/dense-shift alternative that this
experiment RETRACTED rather than answered. Break DATES are still never stored or
compared -- arm C changes nothing about that, and no date-location claim is made.

Run:  uv run python experiments/k1623/k1623_rev3_armc_mc.py
"""
